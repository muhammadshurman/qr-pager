import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { render, screen } from '@testing-library/react'
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest'

import { STAFF_STATES, StaffState } from '../src/staff/StaffState.tsx'

/**
 * ================================================================================
 * `§12`'s "no empty state without a next action", PROVEN AGAINST THE COMPILER
 * ================================================================================
 *
 * `StaffState`'s whole reason for existing beside `StateView` is one rule the customer kit
 * cannot express: `empty`, `error` and `offline` **require** an action. It is enforced by a
 * discriminated union, which means the guard is the TYPE — and a type that happened to admit
 * the bad shape would read identically to one that does not.
 *
 * So it is proven the way every other guard in this repository is: on a committed
 * deliberately-wrong file, with a GOOD file as the control. Without the control, the bad
 * case would pass against a `tsc` invocation that fails on anything at all.
 *
 * ⚠ THE TSCONFIG IS GENERATED BY `extends`, NOT RESTATED. Writing the flags out here would be
 * a second source for `exactOptionalPropertyTypes`, `strict` and the JSX setting — and a
 * weaker one than the real build's, which would make this prove the rule under a compiler
 * nobody ships. It extends `packages/ui/tsconfig.json`.
 *
 * ⚠ AND AN EXPLICIT 60-SECOND TIMEOUT, because this spawns a compiler. Vitest's default is
 * 5 s, which is a UNIT-test default, and the 2026-10-31 decision-log row records a gate step
 * failing in CI and passing locally for exactly that reason.
 */

const UI = join(import.meta.dirname, '..')

/**
 * ⚠ THE SCRATCH TREE IS INSIDE THE PACKAGE, AND THE CONTROL IS WHAT FORCED THAT.
 *
 * The first version compiled in `os.tmpdir()`, and the control fixture failed with *"Cannot
 * find type definition file for 'node'"*, `'react'` and `'react-dom'` — three errors that are
 * nothing to do with the rule. A directory outside the workspace reaches no `node_modules`,
 * so `tsc` could not resolve the `types` the real tsconfig names, and the BAD fixture would
 * have been reported as refused for a reason the rule had no part in.
 *
 * That is the whole purpose of the control, caught on its first run. The scratch tree now
 * sits at `test/.generated/`, which is two directories below the package root — the same
 * depth as `test/fixtures/`, so the fixtures' `../../src/...` import resolves — and is
 * `exclude`d in `packages/ui/tsconfig.json` so `pnpm typecheck` never reads it as source.
 */
const SCRATCH = join(UI, 'test', '.generated')

/*
 * ⚠ REMOVED AT BOTH ENDS, AND THE `beforeAll` HALF IS NOT BELT-AND-BRACES. A run killed
 * between `compile()` and `afterAll` leaves a `.tsx` in the tree, and the next `pnpm gate`
 * then lints it -- or races it, which is what happened: step 1 died with
 * `ENOENT ... staff-state-without-action.tsx` because ESLint enumerated the file and it was
 * gone before the read. The directory is now ignored by all three walkers, and this makes a
 * crashed run unable to leave anything behind in the first place.
 */
beforeAll(() => {
  rmSync(SCRATCH, { recursive: true, force: true })
})

afterAll(() => {
  rmSync(SCRATCH, { recursive: true, force: true })
})

interface Compilation {
  readonly status: number
  readonly output: string
}

function compile(fixture: string): Compilation {
  const name = fixture.replace(/\.fixture$/, '')
  const source = readFileSync(join(UI, 'test', 'fixtures', fixture), 'utf8')
  const file = join(SCRATCH, name)

  mkdirSync(SCRATCH, { recursive: true })
  writeFileSync(file, source, 'utf8')

  const config = join(SCRATCH, `tsconfig.${name}.json`)

  // ⚠ `extends` RATHER THAN A RESTATED FLAG LIST. Writing `strict`,
  // `exactOptionalPropertyTypes` and the JSX setting out here would be a second source for
  // them, and a weaker one than the real build's -- which would make this prove the rule
  // under a compiler nobody ships. `noUnusedLocals` is relaxed because a fixture's exports
  // are never imported.
  writeFileSync(
    config,
    JSON.stringify({
      extends: '../../tsconfig.json',
      compilerOptions: { noEmit: true, noUnusedLocals: false, noUnusedParameters: false },
      include: [name],
      // ⚠ `exclude: []`, AND THE CONTROL CAUGHT THIS TOO. The parent tsconfig excludes
      // `test/.generated/**` -- which is exactly this directory, and `extends` inherits it --
      // so the generated config's `include` matched nothing and `tsc` answered
      // `TS18003: No inputs were found`. One non-zero exit, no mention of `action`, and the
      // bad fixture would have been credited as refused by the rule. Overridden here rather
      // than by weakening the parent's exclude, which is what keeps the scratch tree out of
      // `pnpm typecheck`.
      exclude: [],
    }),
    'utf8',
  )

  const result = spawnSync(
    'node',
    [join(UI, '..', '..', 'node_modules', 'typescript', 'bin', 'tsc'), '-p', config],
    { encoding: 'utf8', cwd: UI },
  )

  rmSync(file, { force: true })

  // `spawnSync`'s stdout/stderr are typed as strings when `encoding` is set, so `??` on
  // them is provably dead; `status` genuinely may be null when the child was signalled.
  return { status: result.status ?? 1, output: `${result.stdout}${result.stderr}` }
}

describe('the staff state type', () => {
  it('COMPILES the correct shapes — the control, without which the next case proves nothing', () => {
    const control = compile('staff-state-with-action.tsx.fixture')

    expect(control.status, `the control fixture did not compile:\n${control.output}`).toBe(0)
    expect(control.output.trim()).toBe('')
  }, 60_000)

  it('REFUSES an empty, error or offline state with no action', () => {
    const bad = compile('staff-state-without-action.tsx.fixture')

    expect(bad.status, 'an actionless empty state compiled, so §12 is unenforced').not.toBe(0)

    // ⚠ THE ERROR NAMES `action`, not merely "some error happened". A red for an unresolved
    // import or a bad JSX setting would also be non-zero, and that is the shape the control
    // above is for -- this is the second half of the same guard.
    expect(bad.output).toContain('action')

    // All three renders are reported, not just the first: a union that refused `empty` and
    // admitted `offline` would satisfy a one-error assertion.
    const errors = [...bad.output.matchAll(/error TS\d+/g)].length

    expect(errors, `expected three type errors, got ${String(errors)}:\n${bad.output}`).toBe(3)
  }, 60_000)

  it('REFUSES a throttled state that offers an action — R-224, in the type', () => {
    // THE MIRROR OF THE CASE ABOVE rather than more of the same. That one proves `§12`'s
    // *no empty state without a next action*; this one proves Muhammad's `R-224` ruling
    // that a throttled board offers NOTHING to press, because the backoff is already
    // doing the only thing that works.
    const bad = compile('staff-state-throttled-with-action.tsx.fixture')

    expect(
      bad.status,
      'a throttled state with an action compiled, so R-224 is unenforced',
    ).not.toBe(0)

    // Names `action`, not merely "some error": an unresolved import would also be
    // non-zero, which is what the control fixture exists to separate out.
    expect(bad.output).toContain('action')

    const errors = [...bad.output.matchAll(/error TS\d+/g)].length

    expect(errors, `expected one type error, got ${String(errors)}:\n${bad.output}`).toBe(1)
  }, 60_000)
})

describe('the staff state at run time', () => {
  it('knows all seven states and renders each one distinguishably', () => {
    // The list is exported so a test must cover all of it; a state added without a branch
    // would render nothing and this would catch it. `throttled` arrived at 10b (`R-224`).
    expect([...STAFF_STATES]).toEqual([
      'ready',
      'loading',
      'empty',
      'error',
      'offline',
      'permission-denied',
      'throttled',
    ])
  })

  it('announces error and offline, and does not announce empty, permission-denied or throttled', () => {
    // `error` and `offline` are events and interrupt; `empty`, `permission-denied` and
    // `throttled` are answers. Announcing an answer makes a screen reader shout a
    // non-event -- and for `throttled` that is `R-224`'s *no message on the first 429*
    // arriving through the accessibility tree rather than through the paint.
    for (const state of ['error', 'offline'] as const) {
      const { container, unmount } = render(
        <StaffState
          state={state}
          title="t"
          description="d"
          action={{ label: 'a', onAction: vi.fn() }}
        />,
      )

      expect(container.querySelector('[role="alert"]'), state).not.toBeNull()
      unmount()
    }

    for (const state of ['permission-denied', 'throttled'] as const) {
      const { container, unmount } = render(<StaffState state={state} title="t" description="d" />)

      expect(container.querySelector('[role="alert"]'), state).toBeNull()
      unmount()
    }
  })

  it('offers NO button on a throttled board, which is R-224 ruled rather than styled', () => {
    // The run-time half of the fixture guard below. Muhammad's ruling: *"on the board
    // nothing is required of the person and it resumes itself"* -- so the only honest
    // affordance is none, and a button here would have exactly one effect, another 429.
    const { container } = render(
      <StaffState
        state="throttled"
        title="The board is catching up."
        description="It will refresh itself in a moment."
      />,
    )

    expect(container.querySelector('button')).toBeNull()
    expect(container.querySelector('[data-state="throttled"]')).not.toBeNull()
  })

  it('gives the loading state an accessible name rather than a bare spinner', () => {
    render(<StaffState state="loading" loadingLabel="Loading the board" />)

    // Twice: once visually hidden for the control's own name, once in a live region so a
    // screen reader is told the wait has begun. A spinner with no name says nothing.
    expect(screen.getAllByText('Loading the board').length).toBeGreaterThanOrEqual(1)
  })

  it('renders its children and nothing of its own in the ready state', () => {
    const { container } = render(<StaffState state="ready">the board</StaffState>)

    expect(container.textContent).toBe('the board')
    expect(container.querySelector('.qr-staff-state')).toBeNull()
  })
})

import { existsSync, readFileSync } from 'node:fs'
import { join, relative } from 'node:path'

import { describe, expect, it } from 'vitest'

import { ARTEFACTS } from '../scripts/generate.mjs'
import { FONTS } from '../src/source.ts'

const PKG = join(import.meta.dirname, '..')
const REPO = join(PKG, '..', '..')
const read = (p: string) => readFileSync(join(REPO, p), 'utf8')

/**
 * ================================================================================
 * EVERY FILE PATH A GENERATED ARTEFACT NAMES MUST RESOLVE ON DISK
 * ================================================================================
 *
 * ⚠ THE CLASS, NOT THE LINE. `apps/api/config/design-tokens.php` named
 * `tajawal-arabic.woff2` for the whole of this task. That file has never existed -- the
 * faces are `-400` and `-700` -- and **nothing could see it**:
 *
 *   - `pnpm tokens:check` byte-diffs each artefact against what the source produces right
 *     now, so it proved the artefact was CURRENT, which it was. Staleness and truth are
 *     different properties, and only one of them was ever checked.
 *   - `fonts.test.ts` checks every path in `fonts.css` and in `PROVENANCE.json`, both of
 *     which are written by the FETCH script from the files it actually fetched. It never
 *     read `FONTS.*.file`, because no artefact it covers is built from it.
 *   - the PHP config's only consumer is Filament in 8b, which does not exist yet, so no
 *     runtime would have opened it either.
 *
 * So the defect's shape is: **every generated artefact is proven STALE-checked and none is
 * proven EXISTENCE-checked.** This file is the second half. It takes the artefact list from
 * the generator itself -- `ARTEFACTS`, the same array `tokens:check` walks -- so an artefact
 * added later is covered without anybody remembering this file, and it adds the two the
 * fetch script writes, which are generated by a different script and are therefore not in
 * that array.
 *
 * WHAT COUNTS AS A PATH is deliberately broad: anything that looks like a filename with a
 * known extension, and anything that looks like a repo-relative path. A pattern that only
 * matched `.woff2` would have caught this one defect and nothing else.
 */

/** Extensions a generated artefact may name, with where a bare filename is resolved from. */
const BARE_FILENAME_ROOTS: Readonly<Record<string, string>> = {
  '.woff2': 'packages/tokens/fonts',
  '.woff': 'packages/tokens/fonts',
  '.ttf': 'packages/tokens/fonts',
  '.otf': 'packages/tokens/fonts',
}

const EXTENSIONS = [
  '.woff2',
  '.woff',
  '.ttf',
  '.otf',
  '.css',
  '.ts',
  '.tsx',
  '.mjs',
  '.js',
  '.php',
  '.json',
  '.md',
  '.html',
  '.svg',
  '.png',
  '.jpg',
  '.webp',
]

/**
 * Every path-looking string in a source, with the position that found it.
 *
 * Two shapes: a repo-relative path (`packages/tokens/src/source.ts`), and a bare filename
 * with one of the font extensions, which resolves against the font directory. A URL is
 * skipped -- `fonts.test.ts` already asserts there are none, and a remote URL is not a path
 * this check could resolve anyway.
 */
function pathsIn(source: string): { raw: string; candidates: string[] }[] {
  const out: { raw: string; candidates: string[] }[] = []
  const seen = new Set<string>()
  const extensions = EXTENSIONS.map((e) => e.replace('.', '\\.')).join('|')
  const re = new RegExp(`[A-Za-z0-9._/-]+(?:${extensions})\\b`, 'g')

  for (const match of source.matchAll(re)) {
    const raw = match[0]
    if (seen.has(raw)) continue
    seen.add(raw)

    // A URL's path component is not a path on this disk. The character class above excludes
    // `:`, so a match inside `https://fonts.gstatic.com/…` BEGINS at the `//` -- which is
    // what this rejects, together with anything the scheme's colon precedes directly.
    const at = match.index
    const preceding = at === 0 ? '' : source[at - 1]
    if (raw.startsWith('//') || preceding === ':') continue
    // A package specifier (`@qrpager/ui/kit.css`, `tailwindcss`) is resolved by a bundler,
    // not by this repo's layout.
    if (raw.startsWith('@') || raw.startsWith('node_modules/')) continue

    const cleaned = raw.replace(/^\.\//, '')
    const extension = EXTENSIONS.find((e) => cleaned.endsWith(e))
    if (extension === undefined) continue

    if (cleaned.includes('/')) {
      // A path in a file is relative to SOMETHING, and which something differs: the banner
      // of `generated/tokens.css` names `generated/contrast.md` relative to its package,
      // while its body names `packages/tokens/src/source.ts` relative to the repo. The
      // check's job is to catch a name that resolves to nothing ANYWHERE, so every root a
      // reader could reasonably read it against is offered -- and a name like
      // `tajawal-arabic.woff2` still resolves under none of them.
      out.push({ raw, candidates: [cleaned] })
      continue
    }
    const root = BARE_FILENAME_ROOTS[extension]
    // A bare filename with a non-font extension is prose (`source.ts`, `README.md`) and is
    // covered by the relative-path branch when it is actually a path.
    if (root !== undefined) out.push({ raw, candidates: [`${root}/${cleaned}`] })
  }
  return out
}

/**
 * The roots a relative path inside one artefact may be read against: the repo, the
 * artefact's own directory, and its package root.
 */
function rootsFor(artefact: string): string[] {
  const parts = artefact.split('/')
  const roots = new Set<string>([''])
  roots.add(parts.slice(0, -1).join('/'))
  // `packages/tokens/generated/tokens.css` -> `packages/tokens`
  if (parts[0] === 'packages' || parts[0] === 'tools' || parts[0] === 'apps') {
    roots.add(parts.slice(0, 2).join('/'))
  }
  return [...roots]
}

/**
 * The generated artefacts, from the generator's own list plus the two the fetch script
 * writes.
 *
 * `ARTEFACTS` carries absolute paths; the fetch script's two are named here because they
 * are produced by `fetch-fonts.mjs` and so appear in no array `generate.mjs` exports.
 */
function generatedArtefacts(): string[] {
  const fromGenerator = (ARTEFACTS as { path: string }[]).map((a) =>
    relative(REPO, a.path).split('\\').join('/'),
  )
  return [
    ...fromGenerator,
    'packages/tokens/fonts/fonts.css',
    'packages/tokens/fonts/PROVENANCE.json',
  ]
}

describe('every path a generated artefact names', () => {
  it('reads a non-empty artefact list from the generator, so this cannot pass vacuously', () => {
    const artefacts = generatedArtefacts()
    expect(artefacts.length).toBeGreaterThanOrEqual(7)
    // The two sources of the list, each present: the generator's array and the fetch
    // script's two outputs. A refactor that empties `ARTEFACTS` fails here rather than
    // making every assertion below trivially true.
    expect(artefacts).toContain('apps/api/config/design-tokens.php')
    expect(artefacts).toContain('packages/tokens/fonts/PROVENANCE.json')
    for (const artefact of artefacts) {
      expect(existsSync(join(REPO, artefact)), `${artefact} does not exist`).toBe(true)
    }
  })

  it('resolves on disk -- the check that would have caught tajawal-arabic.woff2', () => {
    const missing: string[] = []
    let checked = 0

    for (const artefact of generatedArtefacts()) {
      const roots = rootsFor(artefact)
      for (const { raw, candidates } of pathsIn(read(artefact))) {
        checked += 1
        const tried = candidates.flatMap((c) => roots.map((r) => (r === '' ? c : `${r}/${c}`)))
        if (!tried.some((p) => existsSync(join(REPO, p)))) {
          missing.push(`${artefact}: '${raw}' resolves to nothing (tried ${tried.join(', ')})`)
        }
      }
    }

    // A lower bound, so an expression change that stops finding paths reddens here instead
    // of reporting nothing missing over nothing examined.
    expect(checked, 'no path-looking string was found in any artefact').toBeGreaterThan(20)
    expect(missing, 'these generated artefacts name files that do not exist').toEqual([])
  })

  it('names the font faces that are actually on disk, both families', () => {
    // The specific defect, pinned by exact value as well as by the class above -- §8's
    // "assert exact values, never ranges". The class check would catch a regression; this
    // says what the right answer is.
    expect(FONTS.latin.files).toEqual(['plus-jakarta-sans-latin.woff2'])
    expect(FONTS.arabic.files).toEqual(['tajawal-arabic-400.woff2', 'tajawal-arabic-700.woff2'])

    // And the source agrees with the two artefacts the FETCH script writes, which is the
    // join the old singular `file` could not express: Plus Jakarta Sans is variable and is
    // one file for two weights, Tajawal is one file per weight.
    const css = read('packages/tokens/fonts/fonts.css')
    const inCss = new Set([...css.matchAll(/url\('\.\/([^']+)'\)/g)].map((m) => m[1]!))
    const inSource = new Set([...FONTS.latin.files, ...FONTS.arabic.files])
    expect([...inSource].sort()).toEqual([...inCss].sort())

    const provenance = JSON.parse(read('packages/tokens/fonts/PROVENANCE.json')) as {
      faces: readonly { file: string }[]
    }
    expect([...inSource].sort()).toEqual(provenance.faces.map((f) => f.file).sort())
  })
})
